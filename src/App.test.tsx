test('для двух направлений предлагает один приоритет и добавляет открытие по переключателю', async () => {
  const user = userEvent.setup()
  renderWithChakra(<App />)
  await user.click(checkbox('Данные и визуализация'))
  await user.click(checkbox('Люди и психология'))
  await next(user)
  await user.click(checkbox('Объяснять результаты команде'))
  await next(user)
  await user.click(checkbox('Проводить наблюдения и интервью'))
  await next(user)
  await user.click(checkbox('Применить на работе'))
  await next(user)
  expect(screen.getByRole('heading', { name: 'Что поставить на первое место?' })).toHaveFocus()
  expect(screen.getByRole('radio', { name: 'Все интересы на равных' })).toBeChecked()
  await user.click(screen.getByRole('radio', { name: 'Данные и визуализация' }))
  expect(screen.getByRole('radio', { name: 'Люди и психология' })).not.toBeChecked()
  await user.click(button('Посмотреть подборку'))

  const recommendations = within(await screen.findByRole('region', { name: 'Рекомендации' }))
  expect(recommendations.getByRole('article', { name: /Анализ данных и инфографика/ })).toBeVisible()
  const field = within(recommendations.getByRole('article', { name: /Первый выход в поле/ }))
  expect(field.getByRole('link', { name: 'Открыть на сайте ВШЭ' }))
    .toHaveAttribute('href', 'https://www.hse.ru/edu/courses/1189299751')
  expect(field.getByText(/ · Санкт-Петербург$/)).toBeVisible()
  expect(recommendations.getByText(/Другой ракурс/)).toBeVisible()
  await user.click(button('По выбранному'))
  expect(button('По выбранному')).toHaveAttribute('aria-pressed', 'true')
  expect(recommendations.queryByText(/Другой ракурс/)).not.toBeInTheDocument()
  await user.click(button('Добавить открытие'))
  expect(recommendations.getByText(/Другой ракурс/)).toBeVisible()
})

test('учитывает интерес из чата, сохраняет выбранное направление и показывает отсутствие совпадений', async () => {
  const user = userEvent.setup()
  renderWithChakra(<App />)
  await user.click(checkbox('Данные и визуализация'))
  await user.click(screen.getByRole('link', { name: 'Расскажу в чате' }))
  const heading = await screen.findByRole('heading', { name: 'Чат по факультативам', level: 1 })
  expect(heading).toHaveFocus()
  expect(window.location.hash).toBe('#/chat')
  const input = screen.getByRole('textbox', { name: 'Запрос по каталогу' })
  await user.type(input, 'исследовательские интервью{Enter}')
  button('Учесть в подборке').focus()
  await user.keyboard('{Enter}')
  expect(screen.getByText('Учтено в подборке')).toBeVisible()
  expect(input).toHaveFocus()
  await user.click(button('К анкете'))

  expect(await screen.findByRole('checkbox', { name: 'Данные и визуализация' })).toBeChecked()
  expect(button('Удалить интерес исследовательские интервью')).toBeVisible()

  await user.click(screen.getByRole('link', { name: 'Расскажу в чате' }))
  expect(await screen.findByText('исследовательские интервью', { exact: true })).toBeVisible()
  await user.type(screen.getByRole('textbox', { name: 'Запрос по каталогу' }), 'архитектура марсианских станций{Enter}')
  await user.click(button('Учесть в подборке'))
  await user.click(button('К анкете'))
  await user.click(await screen.findByRole('button', { name: 'Уже показать подборку' }))
  expect(await screen.findByRole('article', { name: /Первый выход в поле/ })).toBeVisible()
  expect(screen.getByText(/марсианских станций.*пока нет совпадений/)).toBeVisible()
  await user.click(button('Изменить интересы'))
  await user.click(button('Удалить интерес архитектура марсианских станций'))
  expect(screen.queryByRole('button', { name: /Удалить интерес архитектура/ })).not.toBeInTheDocument()
})

