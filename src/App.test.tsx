  expect(checkbox('Тексты и языковые модели · NLP')).toBeChecked()
  await user.click(button('Уже показать подборку'))
  expect(screen.getByRole('heading', { name: 'Твоя подборка' })).toHaveFocus()
  const card = within(await screen.findByRole('article', { name: /Упаковка информации/ }))
  expect(card.getByText(/контекст и интонация/)).toBeVisible()
