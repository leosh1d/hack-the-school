test('выбирает лимит контактных часов клавиатурой и восстанавливает его при возврате', async () => {
  const user = userEvent.setup()
  renderWithChakra(<App />)
  await chooseCoding(user)

  const wheel = () => screen.getByRole('listbox', { name: 'Сколько контактных часов вы готовы выделить?' })
  const selected = () => within(wheel()).getByRole('option', { selected: true })
  expect(selected()).toHaveTextContent('Без ограничений')
  expect(wheel()).toHaveAttribute('aria-activedescendant', selected().id)
  expect(within(wheel()).getAllByRole('option')).toHaveLength(5)
  await user.tab()
  expect(wheel()).toHaveFocus()
  await user.keyboard('{Home}')
  expect(selected()).toHaveTextContent('До 30 ч')
  await user.keyboard('{ArrowDown}')
  expect(selected()).toHaveTextContent('До 40 ч')
  await user.keyboard('{End}')
  expect(selected()).toHaveTextContent('Без ограничений')
  await user.keyboard('{Home}')
  await next(user)
  await back(user)
  expect(selected()).toHaveTextContent('До 30 ч')
  await next(user)
  await next(user)
  await showResults(user)

  const matches = within(await screen.findByRole('region', { name: 'Рекомендации' }))
  expect(matches.getAllByRole('article')).toHaveLength(1)
  expect(matches.getByRole('article', { name: /молекулярной динамики на языке Julia/ })).toBeVisible()
})

